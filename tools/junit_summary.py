"""Turn JUnit XML reports into a compact Markdown failure table."""

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def _clean_cell(value: str) -> str:
    """Escape text for a Markdown table cell."""
    return " ".join(value.replace("|", "\\|").split())


def render_summary(paths: list[Path]) -> str:
    """Return a Markdown table for failures in any existing JUnit reports."""
    rows: list[tuple[str, str, str, str]] = []
    reports_found = False

    for path in paths:
        if not path.is_file():
            continue
        reports_found = True
        # Reports are generated by this repository's test runners, not arbitrary input.
        root = ET.parse(path).getroot()  # noqa: S314
        for suite in root.iter("testsuite"):
            suite_name = suite.attrib.get("name", path.stem)
            for case in suite.findall("testcase"):
                failure = case.find("failure")
                if failure is None:
                    failure = case.find("error")
                if failure is None:
                    continue
                details = failure.attrib.get("message", "") or (failure.text or "")
                rows.append(
                    (
                        suite_name,
                        case.attrib.get("name", "unknown test"),
                        "error" if failure.tag == "error" else "failure",
                        details,
                    )
                )

    if not reports_found:
        return "No JUnit reports found."
    if not rows:
        return "No test failures found."

    lines = ["| Suite | Test | Result | Details |", "| --- | --- | --- | --- |"]
    for suite, test, result, details in rows:
        lines.append(
            "| " + " | ".join(_clean_cell(item) for item in (suite, test, result, details)) + " |"
        )
    return "\n".join(lines)


def main() -> int:
    """Parse report paths and print their Markdown summary."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reports", nargs="*", type=Path)
    args = parser.parse_args()

    try:
        summary = render_summary(args.reports)
    except ET.ParseError as error:
        print(f"Invalid JUnit XML: {error}", file=sys.stderr)
        return 1

    print(summary)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
